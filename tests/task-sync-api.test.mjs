import {test,after} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,readFileSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {TEAM_TASKS,PERSONAL_TASKS} from '../app/lib/task-sync.mjs';
const directory=mkdtempSync(join(tmpdir(),'tongpin-sync-api-'));
process.env.TONGPIN_DATA_DIR=directory;
delete process.env.TONGPIN_PUBLIC_ORIGIN;
after(()=>rmSync(directory,{recursive:true,force:true}));
const {handleTeam}=await import('../app/lib/team-store.ts');
test('authenticated API persists both views atomically and rejects stale edits from the other view',async()=>{
 const call=async(body,cookie='')=>handleTeam(new Request('http://localhost/api/team',{method:'POST',headers:{cookie,'Content-Type':'application/json'},body:JSON.stringify(body)}));
 await handleTeam(new Request('http://localhost/api/team'));
 const codes=JSON.parse(readFileSync(join(directory,'invitations.json'),'utf8'));
 const cookie=(await call({action:'login',code:codes.xzx})).headers.get('set-cookie').split(';')[0];
 const get=async key=>(await (await handleTeam(new Request('http://localhost/api/team?key='+key,{headers:{cookie}}))).json()).document;
 const post=async(key,doc,value)=>call({key,revision:doc?.revision||0,value},cookie);
 let personal=await get(PERSONAL_TASKS);
 let response=await post(PERSONAL_TASKS,personal,[{id:1,title:'跨视图测试',owner:'xzx',category:'生活',due:null,done:false,note:'保留换行\n下一步',startTime:'10:00',endTime:'11:00'},{id:2,title:'独立私事',owner:'xzx',category:'独立',due:null,done:false,note:'',startTime:'10:00',endTime:'11:00'}]);
 assert.equal(response.status,200);personal=(await response.json()).document;
 let team=await get(TEAM_TASKS);
 assert.equal(team.value.length,1);assert.equal(team.value[0].status,'待完成');
 assert.equal(personal.value[0].teamTaskId,team.value[0].id);
 const stalePersonal=structuredClone(personal);
 response=await post(TEAM_TASKS,team,team.value.map(t=>({...t,owner:'czl',due:'2026-10-21',status:'进行中',description:'协作修改',reviews:[{id:101,text:'讨论'}]})));
 assert.equal(response.status,200);team=(await response.json()).document;
 assert.equal((await post(PERSONAL_TASKS,stalePersonal,stalePersonal.value)).status,409);
 personal=await get(PERSONAL_TASKS);
 assert.deepEqual([personal.value[0].owner,personal.value[0].due,personal.value[0].note],['czl','2026-10-21','协作修改']);
 response=await post(PERSONAL_TASKS,personal,personal.value.map(p=>p.id===1?{...p,done:true}:p));
 assert.equal(response.status,200);
 assert.equal((await post(TEAM_TASKS,team,team.value)).status,409);
 team=await get(TEAM_TASKS);assert.equal(team.value[0].status,'已完成');assert.equal(team.value[0].reviews[0].text,'讨论');
 personal=await get(PERSONAL_TASKS);
 response=await post(PERSONAL_TASKS,personal,personal.value.map(p=>p.id===1?{...p,category:'独立'}:p));
 assert.equal(response.status,200);assert.equal((await get(TEAM_TASKS)).value.length,0);
 assert.equal((await get(PERSONAL_TASKS)).value.length,2);
 const disk=JSON.parse(readFileSync(join(directory,'workspace.json'),'utf8'));
 assert.equal(disk.taskSyncVersion,1);
 assert.equal(disk.documents[TEAM_TASKS].value.length,0);
 assert.equal(disk.documents[PERSONAL_TASKS].value[0].collaborationDetails.reviews[0].text,'讨论');
});
